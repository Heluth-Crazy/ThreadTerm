export const themePackById = new Map(themePacks.map((pack) => [pack.id, pack]));

export function getThemePack(
  themePackId: string | null | undefined,
  availableThemePacks: ThemePack[] = themePacks,
): ThemePack {
  return (
    availableThemePacks.find((pack) => pack.id === themePackId) ??
    availableThemePacks.find((pack) => pack.id === DEFAULT_THEME_PACK_ID) ??
    themePackById.get(DEFAULT_THEME_PACK_ID)!
  );
}

export function getThemePackIds(): string[] {
  return themePacks.map((pack) => pack.id);
}
